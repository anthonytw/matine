import Foundation

/// Renders a `ConversionPlan` as one POSIX sh script for the NAS host, to be
/// read once and run by the owner. Properties the script keeps:
///
/// - Only the literal `DRY_RUN=0` does anything: every other value (unset,
///   `1`, `yes`, a typo) is a dry run that only tests (read-only) and echoes.
/// - `MODE` is exactly `run` or `undo`, else usage and exit 2.
/// - Each file's ffmpeg and ffprobe run in a one-off container of the
///   Jellyfin image (media bind-mounted at the same `/media`, so the paths are
///   Jellyfin's own); everything else is plain file moves on the host.
/// - The output is written to a dot-named temp file beside the original
///   (Jellyfin's scanner ignores dot-files and dot-folders: `**/.*`), checked
///   with ffprobe, and only then swapped in: the original moves to a sibling
///   `.matine-originals/`, never deleted. Every move refuses to overwrite and
///   is checked afterwards (`mv -n` exits 0 when it skips).
/// - Before each ffmpeg run the folder's free space is checked (file x 1.1 plus
///   a reserve, `RESERVE_GB`, 20 by default); too little stops the whole run.
/// - A file already done (an original set aside) is skipped; a swap that was
///   interrupted between its two moves is finished on the next run. Stop it
///   at any time and run it again. One run at a time (a lock folder).
/// - Each swap logs an `intent` line before and a `done` line after
///   (`phase, old path, new path, verdict`, tab-separated) to a log on the
///   media disk. `undo` replays the intents newest-first, then the step list
///   embedded in the script, so it works without the log.
public enum ConversionScript {
    public static func render(_ plan: ConversionPlan, command: String = "matine convert-plan") -> String {
        var out = prelude(plan, command: command)
        for (number, step) in plan.steps.enumerated() {
            out += function(number + 1, of: plan.steps.count, step)
        }
        out += "\n# The steps of THIS script: old path, new path, verdict, extracted subtitle files. `undo` covers only these.\nembedded() {\ncat <<'MATINE_STEPS'\n"
        for step in plan.steps {
            out += ([step.sourcePath, step.outputPath, step.kind.rawValue] + step.sidecars.map(\.path)).joined(separator: "\t") + "\n"
        }
        out += "MATINE_STEPS\n}\n\n"
        out += tail
        out += "echo \"matine convert: \(plan.steps.count) file(s)\"\n"
        out += "FAILS=0\n"
        for number in plan.steps.indices {
            out += "\(name(number + 1)) || FAILS=$((FAILS + 1))\n"
        }
        out += #"""
        if [ "$FAILS" -gt 0 ]; then
          echo "$FAILS file(s) failed: see the messages above. Originals are never deleted: each is either in place or in .matine-originals/"
          exit 1
        fi
        echo done

        """#
        return out
    }

    static func name(_ number: Int) -> String { "convert_\(number)" }

    /// The lock, the mode, and (for undo) the end of the script.
    static let tail = #"""
    if ! is_dry; then
      if ! mkdir "$LOCK" 2>/dev/null; then
        echo "another run holds $LOCK (pid $(cat "$LOCK/pid" 2>/dev/null || echo '?')). If \`kill -0\` says that pid is gone, remove it: rm -r '$LOCK'"
        exit 1
      fi
      echo $$ > "$LOCK/pid"
      trap cleanup EXIT
      trap 'exit 130' INT
      trap 'exit 143' TERM
      trap 'exit 129' HUP
    fi
    if [ "$MODE" = undo ]; then undo; exit 0; fi
    if is_dry; then echo "DRY RUN: nothing is changed (DRY_RUN=0 converts)"; fi

    """#

    static func gigabytes(_ bytes: Int64) -> String { String(format: "%.1f GB", Double(bytes) / 1e9) }

    static func prelude(_ plan: ConversionPlan, command: String) -> String {
        var header = "#!/bin/sh\n# Generated by `\(command)`. Read it before running it.\n"
        let kinds = Dictionary(grouping: plan.steps, by: \.kind).mapValues(\.count)
        header += "# \(plan.steps.count) file(s): "
            + [MediaVerdict.faststart, .remux, .reencode].map { "\(kinds[$0] ?? 0) \($0.rawValue)" }.joined(separator: ", ") + "\n"
        header += "# Disk: about \(gigabytes(plan.bytesNeeded)) (sources x 1.1: the originals stay beside the new files), plus RESERVE_GB (20) kept free.\n"
        let renames = plan.steps.filter(\.isRename).count
        if renames > 0 {
            header += "# \(renames) change(s) the file name (.mkv to .mp4): Jellyfin makes a NEW item for each after a rescan.\n"
            header += "# Run `matine carry-over --snapshot FILE` first and `--restore FILE --apply` after the rescan (per profile).\n"
        }
        if plan.steps.contains(where: { $0.doviCheck == "1" }) {
            header += "# Dolby Vision (dvh1) files need -strict unofficial for their dvcC box: verify checks it, but try ONE such file first.\n"
        }
        for skipped in plan.skipped {
            header += "# left alone: \(comment(skipped.check.file.path ?? skipped.check.file.title)): \(comment(skipped.reason))\n"
        }
        return header + #"""
        #
        #   sh plan.sh              dry run: tests and echoes only
        #   DRY_RUN=0 sh plan.sh    convert (only the literal 0; anything else is a dry run)
        #   sh plan.sh undo         (DRY_RUN=0 to do it) put the originals back: only THIS script's files,
        #                           even if the log holds other plans (the log is shared, on the media disk)
        #
        # Run it under tmux or screen so a dropped SSH session doesn't stop it. It stops cleanly on
        # Ctrl-C, TERM and HUP (the lock goes, the container is killed) and can be rerun. If a run was
        # killed hard (kill -9, power loss):
        #   cat /srv/media/.matine-lock/pid    the pid that held the lock
        #   kill -0 PID                               "No such process" means it is gone: rm -r the lock folder
        #   docker ps --filter label=matine-convert    leftover containers; docker kill NAME stops one
        #
        # Settings (environment): MEDIA_HOST (the media folder on the host, bind-mounted at /media
        # in the containers), IMAGE (ffmpeg comes from the Jellyfin image: jellyfin-ffmpeg 7.x,
        # where FLAC in MP4 needs no flags), RUN_AS (the owner of the media), LOG, RESERVE_GB (whole GB).
        set -eu

        usage() { echo "usage: sh $0 [run|undo]   (DRY_RUN=0 to act; anything else is a dry run)" >&2; exit 2; }
        [ "$#" -le 1 ] || usage
        MODE=${1:-run}
        case $MODE in run|undo) ;; *) usage ;; esac

        DRY_RUN=${DRY_RUN:-1}
        MEDIA_HOST=${MEDIA_HOST:-/srv/media}
        IMAGE=${IMAGE:-jellyfin/jellyfin:12.4@sha256:fea863d0cd9ec445985d9c75fc6ed64e38a1d2766cf0c250a33d553f4fc1b771}
        RUN_AS=${RUN_AS:-1000:1000}
        LOG=${LOG:-$MEDIA_HOST/.matine-convert.tsv}
        LOCK=$MEDIA_HOST/.matine-lock
        RESERVE_GB=${RESERVE_GB-20}
        case $RESERVE_GB in ''|*[!0-9]*) echo "RESERVE_GB must be a whole number of GB, not '$RESERVE_GB'" >&2; exit 2 ;; esac
        case $MEDIA_HOST in *,*) echo "MEDIA_HOST can't contain a comma (docker --mount splits on it): $MEDIA_HOST" >&2; exit 2 ;; esac
        FFN=0

        # What a path looks like in messages: Jellyfin's, not the host's.
        show() { printf '%s' "/media${1#"$MEDIA_HOST"}"; }

        # On exit (also Ctrl-C, TERM, HUP): release the lock and stop this run's container.
        cleanup() {
          rm -f "$LOCK/pid" 2>/dev/null || true
          rmdir "$LOCK" 2>/dev/null || true
          _ids=$(docker ps -q --filter "label=matine-convert=$$" 2>/dev/null || true)
          if [ -n "$_ids" ]; then docker kill $_ids >/dev/null 2>&1 || true; fi
        }

        # Only the literal 0 acts.
        is_dry() { [ "$DRY_RUN" != 0 ]; }

        # ffmpeg and ffprobe, one container per call; no network. Probes mount read-only.
        ffm() { FFN=$((FFN + 1)); docker run --rm --label "matine-convert=$$" --name "matine-convert-$$-$FFN" --network none --user "$RUN_AS" --mount "type=bind,src=$MEDIA_HOST,dst=/media" --entrypoint /usr/lib/jellyfin-ffmpeg/ffmpeg "$IMAGE" "$@"; }
        ffp() { FFN=$((FFN + 1)); docker run --rm --label "matine-convert=$$" --name "matine-convert-$$-$FFN" --network none --user "$RUN_AS" --mount "type=bind,src=$MEDIA_HOST,dst=/media,readonly" --entrypoint /usr/lib/jellyfin-ffmpeg/ffprobe "$IMAGE" "$@"; }

        host() { printf '%s' "$MEDIA_HOST${1#/media}"; }

        # A value as sh would need it typed.
        quote() {
          case $1 in
            ''|*[!A-Za-z0-9_./:=+,@%-]*) printf "'%s'" "$(printf %s "$1" | sed "s/'/'\\\\''/g")" ;;
            *) printf %s "$1" ;;
          esac
        }

        # Runs a command, or on a dry run only shows it.
        act() {
          if is_dry; then
            printf '+'
            for _a in "$@"; do printf ' %s' "$(quote "$_a")"; done
            printf '\n'
          else
            "$@"
          fi
        }

        # move SRC DST: never overwrites, and checks the result (mv -n exits 0 when it skips).
        move() {
          if is_dry; then act mv "$1" "$2"; return 0; fi
          if [ -e "$2" ]; then echo "refusing to overwrite $(show "$2")"; return 1; fi
          mv "$1" "$2" || return 1
          if [ -e "$2" ] && [ ! -e "$1" ]; then return 0; fi
          echo "move FAILED: $(show "$1") -> $(show "$2")"
          return 1
        }

        record() { # phase old new verdict
          if is_dry; then printf '+ log %s: %s -> %s (%s)\n' "$1" "$2" "$3" "$4"
          else printf '%s\t%s\t%s\t%s\n' "$1" "$2" "$3" "$4" >> "$LOG"; fi
        }

        # 0 when the MP4's moov box comes before its mdat: walks the top-level boxes.
        moov_first() {
          _f=$1; _off=0; _n=0
          while [ "$_n" -lt 32 ]; do
            _h=$(dd if="$_f" bs=1 skip="$_off" count=8 2>/dev/null | od -An -v -tu1) || return 1
            set -- $_h
            [ "$#" -eq 8 ] || return 1
            _size=$(( ($1 << 24) + ($2 << 16) + ($3 << 8) + $4 ))
            _type=$(dd if="$_f" bs=1 skip=$((_off + 4)) count=4 2>/dev/null)
            case $_type in moov) return 0 ;; mdat) return 1 ;; esac
            if [ "$_size" -eq 1 ]; then
              _h=$(dd if="$_f" bs=1 skip=$((_off + 8)) count=8 2>/dev/null | od -An -v -tu1) || return 1
              set -- $_h
              [ "$#" -eq 8 ] || return 1
              _size=$(( ($1 << 56) + ($2 << 48) + ($3 << 40) + ($4 << 32) + ($5 << 24) + ($6 << 16) + ($7 << 8) + $8 ))
            fi
            [ "$_size" -ge 8 ] || return 1
            _off=$((_off + _size)); _n=$((_n + 1))
          done
          return 1
        }

        # Stops the whole run when the folder can't take a copy of the file plus the reserve.
        need_space() { # host-file host-dir
          _sz=$(wc -c < "$1" | tr -d ' ')
          _avail=$(df -Pk "$2" | awk 'NR == 2 { print $4 }')
          case $_avail in ''|*[!0-9]*) echo "STOP: can't read the free space of $(show "$2")"; exit 3 ;; esac
          _need=$(( _sz / 1024 * 11 / 10 + RESERVE_GB * 1048576 ))
          if [ "$_avail" -lt "$_need" ]; then
            echo "STOP: $((_avail / 1048576)) GB free in $(show "$2"), need about $((_need / 1048576)) GB (the file x 1.1 + RESERVE_GB=$RESERVE_GB). Nothing more is converted."
            exit 3
          fi
        }

        # One ffprobe per file: stream types, Dolby Vision side data, duration.
        probe() { ffp -v error -show_entries stream=index,codec_type:stream_side_data=side_data_type:format=duration -of compact "$1"; }
        count_kind() { printf '%s\n' "$1" | grep -c "^stream|.*codec_type=$2" || true; }
        duration_of() { printf '%s\n' "$1" | sed -n 's/^format|duration=//p' | head -n 1; }
        # 0 when the first video stream has a DOVI configuration record (ffprobe -of compact puts it on the
        # stream line itself; a separate side_data line is also accepted).
        has_dovi() {
          printf '%s\n' "$1" | awk '
            /^stream\|/ { cur = 0; if ($0 ~ /codec_type=video/ && !seen) { seen = 1; cur = 1; if ($0 ~ /DOVI/) found = 1 } }
            /^side_data\|/ { if (cur && $0 ~ /DOVI/) found = 1 }
            END { exit !found }'
        }

        # verify NEW REFERENCE VIDEO AUDIO SUBTITLE DOVI: stream counts (a number, or "same" as the
        # reference), duration within 0.5 s, the moov box first, and Dolby Vision (0: no check, 1: the
        # first video stream must have a DOVI record, same: as the reference). Container paths.
        verify() {
          if is_dry; then
            echo "+ verify $1 against $2: streams video=$3 audio=$4 subtitle=$5, duration within 0.5 s, moov first, dovi=$6"
            return 0
          fi
          _pn=$(probe "$1") || true
          _pr=$(probe "$2") || true
          for _k in "video:$3" "audio:$4" "subtitle:$5"; do
            _kind=${_k%%:*}; _want=${_k#*:}
            if [ "$_want" = same ]; then _want=$(count_kind "$_pr" "$_kind"); fi
            _got=$(count_kind "$_pn" "$_kind")
            if [ "$_got" != "$_want" ]; then echo "verify FAILED: $_kind streams $_got, expected $_want"; return 1; fi
          done
          _d1=$(duration_of "$_pr"); _d2=$(duration_of "$_pn")
          awk -v a="$_d1" -v b="$_d2" 'BEGIN { if (a == "" || b == "") exit 1; d = a - b; if (d < 0) d = -d; exit !(d <= 0.5) }' \
            || { echo "verify FAILED: duration '$_d1' vs '$_d2'"; return 1; }
          case $6 in
            1) has_dovi "$_pn" || { echo "verify FAILED: no Dolby Vision configuration (dvcC/dvvC) on the first video stream: ffmpeg needs -strict unofficial"; return 1; } ;;
            same) if has_dovi "$_pr" && ! has_dovi "$_pn"; then echo "verify FAILED: the Dolby Vision configuration was lost"; return 1; fi ;;
          esac
          moov_first "$(host "$1")" || { echo "verify FAILED: moov is not first"; return 1; }
        }

        # A sidecar must exist and not be empty (nothing to check on a dry run).
        nonempty() { if is_dry; then return 0; fi; [ -s "$1" ]; }

        # Puts an extracted subtitle beside the file; one that is already there stays.
        sidecar_place() { # temp final (host paths)
          if [ -e "$2" ]; then echo "note: $(show "$2") exists, keeping it"; act rm -f "$1"; else move "$1" "$2"; fi
        }

        # begin KIND SRC DST TEMP ORIGINAL: sets HS HD HT HO REF RESUME; returns 1 for "nothing to do".
        begin() {
          KIND=$1; S=$2; D=$3; T=$4; O=$5
          HS=$(host "$S"); HD=$(host "$D"); HT=$(host "$T"); HO=$(host "$O"); REF=$S; RESUME=0; SWAPPED=0
          if [ ! -e "$HS" ]; then
            if [ -e "$HT" ] && [ -e "$HO" ] && [ ! -e "$HD" ]; then
              echo "resume: finishing an interrupted swap of $D"; REF=$O; RESUME=1; return 0
            fi
            echo "skip: $S is gone (already converted?)"; return 1
          fi
          if [ -e "$HO" ]; then echo "skip: $S already has its original set aside"; return 1; fi
          if [ "$D" != "$S" ] && [ -e "$HD" ]; then echo "skip: $D already exists"; return 1; fi
          if [ "$KIND" = faststart ] && moov_first "$HS"; then echo "skip: $S already has its index first"; return 1; fi
          return 0
        }

        # The swap: original aside (never deleted), then the new file into place.
        swap() {
          record intent "$S" "$D" "$KIND" || return 1
          act mkdir -p "${HO%/*}" || return 1
          act chown "$RUN_AS" "${HO%/*}" 2>/dev/null || true
          # The new file takes the original's owner, group and mode (GNU coreutils on the host; a file
          # ffmpeg wrote as RUN_AS would otherwise keep that owner). Nothing is moved yet, so a failure is safe.
          act chown --reference="$(host "$REF")" "$HT" || return 1
          act chmod --reference="$(host "$REF")" "$HT" || return 1
          act touch -r "$(host "$REF")" "$HT" || return 1
          if [ "$RESUME" != 1 ]; then move "$HS" "$HO" || return 1; fi
          SWAPPED=1
          move "$HT" "$HD" || return 1
          record done "$S" "$D" "$KIND"
        }

        # Restores one original; the converted file (and sidecars extracted for it) go to .matine-converted/TS/, not the bin.
        undo_one() { # old new quiet|loud
          _hold=$(host "$1"); _hnew=$(host "$2")
          _hor="${_hold%/*}/.matine-originals/${_hold##*/}"
          if [ ! -e "$_hor" ]; then if [ "$3" = loud ]; then echo "skip: no original set aside for $1"; fi; return 0; fi
          if [ "$2" != "$1" ] && [ -e "$_hold" ]; then echo "skip: $1 exists"; return 0; fi
          if [ -e "$_hnew" ]; then
            _dir="${_hnew%/*}/.matine-converted/$TS"
            act mkdir -p "$_dir" || return 1
            act chown "$RUN_AS" "${_hnew%/*}/.matine-converted" "$_dir" 2>/dev/null || true
            move "$_hnew" "$_dir/${_hnew##*/}" || { echo "FAILED: could not set $2 aside"; return 1; }
          fi
          move "$_hor" "$_hold" || { echo "FAILED: could not restore $1 (it is in .matine-originals/)"; return 1; }
          # No globbing: a sidecar name with *, ? or [ must stay literal.
          set -f
          for _side in $(printf '%s\n' "$_steps" | awk -F'\t' -v o="$1" '$1 == o { for (i = 4; i <= NF; i++) print $i }' | tr ' ' '\001'); do
            _side=$(printf %s "$_side" | tr '\001' ' ')
            _hside=$(host "$_side")
            if [ -e "$_hside" ]; then
              act mkdir -p "${_hside%/*}/.matine-converted/$TS" || return 1
              move "$_hside" "${_hside%/*}/.matine-converted/$TS/${_hside##*/}" || echo "note: could not set $_side aside"
            fi
          done
          set +f
          echo "restored: $1"
        }

        # Newest log entries first, then the embedded step list (what the log may not have).
        undo() {
          TS=$(date +%Y%m%d-%H%M%S)-$$
          _tab=$(printf '\t'); _nl=$(printf '\n.'); _nl=${_nl%.}; _fails=0
          _steps=$(embedded)
          if [ -f "$LOG" ]; then
            _lines=$(awk '{ a[NR] = $0 } END { for (i = NR; i > 0; i--) print a[i] }' "$LOG")
            while IFS=$_tab read -r _phase _old _new _kind; do
              [ "$_phase" = intent ] || continue
              # The log is shared with other plans: only this script's own steps.
              case "$_nl$_steps$_nl" in *"$_nl$_old$_tab$_new$_tab"*) ;; *) continue ;; esac
              undo_one "$_old" "$_new" loud || _fails=$((_fails + 1))
            done <<MATINE_LOG
        $_lines
        MATINE_LOG
          else
            echo "no log at $LOG: undoing from the steps in this script"
          fi
          _lines=$_steps
          while IFS=$_tab read -r _old _new _kind; do
            [ -n "$_old" ] || continue
            undo_one "$_old" "$_new" quiet || _fails=$((_fails + 1))
          done <<MATINE_EMBEDDED
        $_lines
        MATINE_EMBEDDED
          if [ "$_fails" -gt 0 ]; then echo "$_fails restore(s) failed"; exit 1; fi
        }

        """#
    }

    static func function(_ number: Int, of total: Int, _ step: ConversionStep) -> String {
        let q = ShellQuote.quote
        var body = "\(name(number))() {\n"
        let label = "[\(number)/\(total)] \(step.kind.rawValue): \(step.sourcePath)"
        body += "  printf '%s\\n' \(q(label))\n"
        for note in step.notes { body += "  # \(ConversionScript.comment(note))\n" }
        body += "  begin \(step.kind.rawValue) \(q(step.sourcePath)) \(q(step.outputPath)) \(q(step.tempPath)) \(q(step.originalPath)) || return 0\n"
        // Removes what a failed attempt wrote (a resumed run keeps its finished temp file).
        var cleanBody = "[ \"$RESUME\" = 1 ] || act rm -f \"$HT\""
        for sidecar in step.sidecars { cleanBody += "; act rm -f \"$(host \(q(sidecar.tempPath)))\"" }
        let clean = "{ \(cleanBody); }"
        let cleanFail = "{ \(cleanBody); return 1; }"
        body += "  if [ \"$RESUME\" != 1 ]; then\n"
        body += "    need_space \"$HS\" \"${HT%/*}\"\n"
        body += "    act rm -f \"$HT\" || return 1\n"
        body += "    act ffm \(step.arguments.map(q).joined(separator: " ")) || { echo \"FAILED: ffmpeg\"; \(clean); return 1; }\n"
        body += "  fi\n"
        for sidecar in step.sidecars {
            body += "  act rm -f \"$(host \(q(sidecar.tempPath)))\" || return 1\n"
            // Extracted from the reference: the original, wherever it is now.
            let arguments = sidecar.arguments.map { $0 == step.sourcePath ? "\"$REF\"" : q($0) }.joined(separator: " ")
            body += "  act ffm \(arguments) || { echo \"FAILED: subtitle extraction\"; \(clean); return 1; }\n"
            body += "  nonempty \"$(host \(q(sidecar.tempPath)))\" || { echo \"FAILED: the extracted subtitle is empty\"; \(clean); return 1; }\n"
        }
        let counts = step.expected.map { "\($0.video) \($0.audio) \($0.subtitle)" } ?? "same same same"
        body += "  verify \(q(step.tempPath)) \"$REF\" \(counts) \(step.doviCheck) || \(cleanFail)\n"
        body += "  swap || { if [ \"$SWAPPED\" = 1 ]; then echo \"FAILED after the original was set aside: it is in $O, the new file is beside it as .matine-part.*; run again\"; else echo \"FAILED before anything was moved: $S is untouched\"; fi; return 1; }\n"
        for sidecar in step.sidecars {
            body += "  sidecar_place \"$(host \(q(sidecar.tempPath)))\" \"$(host \(q(sidecar.path)))\" || { echo \"FAILED: subtitle file \(ConversionScript.comment(sidecar.path)); the converted file is in place and the original is in .matine-originals/\"; return 1; }\n"
        }
        body += "}\n\n"
        return body
    }

    /// A comment line can't hold a newline.
    static func comment(_ text: String) -> String {
        String(String.UnicodeScalarView(text.unicodeScalars.map { $0.value < 0x20 ? " " : $0 }))
    }
}
